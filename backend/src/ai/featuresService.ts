  /**
   * Status overview of user's AI configuration
   */
  public static getUserStatus(userId: string) {
    const connections = db.prepare('SELECT id, provider, name, key_mask, default_model, is_enabled, last_status, last_tested_at FROM user_ai_connections WHERE user_id = ?').all(userId) as any[];
    const permissions = AIContextPermissionService.getPermissions(userId);
    const limits = db.prepare('SELECT * FROM user_ai_spending_limits WHERE user_id = ?').get(userId) as any;

    return {
      userId,
      isConfigured: connections.some(c => c.is_enabled),
      activeConnectionsCount: connections.filter(c => c.is_enabled).length,
      connections,
      permissions,
      spendingLimits: limits || { isSuspended: false, dailyBudgetUsd: 5.0, monthlyBudgetUsd: 50.0 },
      featuresAvailable: [
        'personal_reflection_assistant',
        'relationship_assistant',
        'conversation_assistant',
        'profile_writing_assistant',
        'question_generator',
        'daily_content_generator',
        'communication_analysis',
        'personal_knowledge_retrieval',
        'relationship_memory_retrieval',
        'educational_explanations'
      ],
      mode: connections.some(c => c.is_enabled) ? 'byoai_live_inference' : 'offline_sanctuary_heuristics'
    };
  }
