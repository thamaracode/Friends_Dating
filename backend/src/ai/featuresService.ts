  // =========================================================================
  // 8. Personal Knowledge Retrieval (RAG over user journals & values)
  // =========================================================================
  public static async runPersonalKnowledgeRetrieval(userId: string, query: string): Promise<AIFeatureResult> {
    const permissions = AIContextPermissionService.getPermissions(userId);
    const sourceRefs: SourceReference[] = [];
    const matchedExtracts: string[] = [];

    if (permissions.allowJournals) {
      // Keyword/semantic search over user's answers
      const q = `%${this.sanitizeInput(query)}%`;
      const answers = db.prepare(`
        SELECT a.id, a.answer_text, a.created_at, c.title
        FROM content_answers a
        JOIN content_items c ON a.content_id = c.id
        WHERE a.user_id = ? AND (a.answer_text LIKE ? OR c.title LIKE ?)
        ORDER BY a.created_at DESC LIMIT 4
      `).all(userId, q, q) as any[];

      answers.forEach(ans => {
        matchedExtracts.push(`Journal [${ans.title}]: "${ans.answer_text}"`);
        sourceRefs.push({
          entity: 'content_answer',
          id: ans.id,
          title: ans.title,
          excerpt: ans.answer_text,
          recordedDate: new Date(ans.created_at).toISOString().slice(0, 10)
        });
      });
    }

    // Check personality profile values
    try {
      const prof = db.prepare('SELECT core_values, trait_explanations FROM user_personality_profiles WHERE user_id = ?').get(userId) as any;
      if (prof) {
        matchedExtracts.push(`Core Values: ${prof.core_values}`);
        sourceRefs.push({
          entity: 'personality_profile',
          id: `prof_${userId}`,
          title: 'User Core Values Profile',
          excerpt: prof.core_values
        });
      }
    } catch {
      // fallback
    }

    const systemPrompt = `You are the Soulverse Personal Knowledge Retrieval Engine. Synthesize the user's private reflections to answer their query. Always cite the provided sources and never invent facts.`;
    const userPrompt = `Query: "${query}"\nRetrieved User Context:\n${matchedExtracts.join('\n')}\nSynthesize an answer with direct citations to their notes.`;

    return this.executeWithFallback(userId, 'personal_journal', systemPrompt, userPrompt, () => [
      {
        type: 'user_opinion',
        label: 'Retrieved Personal Records (User Authenticated)',
        content: matchedExtracts.length > 0 
          ? matchedExtracts.join('\n\n')
          : `No matching journal entries found for query "${query}".`,
        sourceReferences: sourceRefs
      },
      {
        type: 'uncertain_interpretation',
        label: 'Synthesized Personal Memory Perspective',
        content: matchedExtracts.length > 0
          ? `Based on your recorded journal reflections, your recurring emphasis is on emotional safety, authenticity, and avoiding resentment through timely boundary setting.`
          : 'Reflect further in the Connection Inquiries sanctuary to build your personal knowledge base.',
        disclaimer: 'Synthesized strictly from your authenticated personal journal entries.'
      }
    ]);
  }

  // =========================================================================
  // 9. Relationship Memory Retrieval (RAG over Relationship Vault)
  // =========================================================================
  public static async runRelationshipMemoryRetrieval(userId: string, personId: string, query: string): Promise<AIFeatureResult> {
    const permissions = AIContextPermissionService.getPermissions(userId);
    const sourceRefs: SourceReference[] = [];
    const factsList: string[] = [];

    // Strict account isolation check
    const person = db.prepare('SELECT * FROM prm_persons WHERE id = ? AND owner_user_id = ?').get(personId, userId) as any;
    if (!person) {
      return {
        featureKey: 'relationship_memory_retrieval',
        featureName: 'RELATIONSHIP MEMORY RETRIEVAL',
        isAiPowered: false,
        providerUsed: 'permission_gate',
        modelUsed: 'none',
        latencyMs: 1,
        blocks: [
          {
            type: 'verified_record',
            label: 'Access Restricted',
            content: 'Person not found or unauthorized access attempt.'
          }
        ]
      };
    }

    sourceRefs.push({
      entity: 'prm_person',
      id: person.id,
      title: person.name,
      excerpt: `Relationship: ${person.relationship_category}, Status: ${person.lifecycle_phase}`
    });

    if (permissions.allowRelationshipVault) {
      const q = `%${this.sanitizeInput(query)}%`;
      const memories = db.prepare(`
        SELECT * FROM prm_memories 
        WHERE person_id = ? AND owner_user_id = ? AND (title LIKE ? OR content LIKE ?)
      `).all(personId, userId, q, q) as any[];

      memories.forEach(m => {
        factsList.push(`Memory [${m.memory_type}]: ${m.title || 'Note'} — ${m.content}`);
        sourceRefs.push({
          entity: 'prm_memory',
          id: m.id,
          title: m.title || 'Memory Record',
          excerpt: m.content,
          recordedDate: m.occurred_at
        });
      });

      const commitments = db.prepare(`
        SELECT * FROM prm_commitments 
        WHERE person_id = ? AND owner_user_id = ? AND description LIKE ?
      `).all(personId, userId, q) as any[];

      commitments.forEach(c => {
        factsList.push(`Commitment: ${c.title} — ${c.description} (Status: ${c.status})`);
        sourceRefs.push({
          entity: 'prm_commitment',
          id: c.id,
          title: c.title,
          excerpt: c.description
        });
      });
    }

    const systemPrompt = `You are the Soulverse Relationship Memory Retrieval Assistant. Answer the query using ONLY the verified facts from the user's private dossier. Never hallucinate conversations or promises not recorded.`;
    const userPrompt = `Query: "${query}"\nDossier for ${person.name}:\n${factsList.join('\n')}\nProvide a factual briefing with source citations.`;

    return this.executeWithFallback(userId, 'relationship_assistant', systemPrompt, userPrompt, () => [
      {
        type: 'verified_record',
        label: `Verified Dossier Records for ${person.name}`,
        content: factsList.length > 0 
          ? factsList.join('\n\n')
          : `No specific memories or commitments matched "${query}" for ${person.name}.`,
        sourceReferences: sourceRefs
      },
      {
        type: 'generated_suggestion',
        label: 'Contextual Recall Briefing',
        content: factsList.length > 0
          ? `You have ${sourceRefs.length - 1} relevant historical notes recorded about ${person.name}. Review exact quotes before your conversation to honor their exact phrasing.`
          : `You have not yet logged specific memories regarding "${query}". Consider recording an interaction in the Relationship Vault.`,
        disclaimer: 'Directly compiled from your private relationship vault.'
      }
    ]);
  }

